/* 轮常数 */
static const uint8_t rcon[10] = {
    0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36,
};

/* GF(2^8) 上的 xtime（乘 x） */
static uint8_t xtime(uint8_t x)
{
    return (uint8_t)((x << 1) ^ ((x & 0x80) ? 0x1b : 0x00));
}

/* GF(2^8) 乘法 */
static uint8_t gmul(uint8_t a, uint8_t b)
{
    uint8_t p = 0;
    for (int i = 0; i < 8; i++) {
        if (b & 1) p ^= a;
        uint8_t hi = a & 0x80;
        a = (uint8_t)(a << 1);
        if (hi) a ^= 0x1b;
        b >>= 1;
    }
    return p;
}

static uint32_t get_word(const uint8_t *b)
{
    return ((uint32_t)b[0] << 24) | ((uint32_t)b[1] << 16) |
           ((uint32_t)b[2] << 8) | (uint32_t)b[3];
}

void aes128_set_encrypt_key(aes128_ctx *ctx, const uint8_t key[AES128_KEY_LEN])
{
    uint32_t *rk = ctx->rk;
    rk[0] = get_word(key);
    rk[1] = get_word(key + 4);
    rk[2] = get_word(key + 8);
    rk[3] = get_word(key + 12);

    for (int i = 4; i < 44; i++) {
        uint32_t t = rk[i - 1];
        if (i % 4 == 0) {
            /* RotWord + SubWord + Rcon */
            t = ((uint32_t)sbox[(t >> 16) & 0xff] << 24) |
                ((uint32_t)sbox[(t >> 8) & 0xff] << 16) |
                ((uint32_t)sbox[t & 0xff] << 8) |
                ((uint32_t)sbox[(t >> 24) & 0xff]);
            t ^= (uint32_t)rcon[i / 4 - 1] << 24;
        }
        rk[i] = rk[i - 4] ^ t;
    }
}

void aes128_encrypt_block(const aes128_ctx *ctx, const uint8_t in[AES_BLOCK_LEN],
                          uint8_t out[AES_BLOCK_LEN])
{
    const uint32_t *rk = ctx->rk;
    uint8_t s[AES_BLOCK_LEN];
    uint8_t t[AES_BLOCK_LEN];

    /* 初始 AddRoundKey */
    for (int i = 0; i < 16; i++) s[i] = in[i];
    for (int i = 0; i < 16; i++) s[i] ^= (uint8_t)(rk[i >> 2] >> (24 - 8 * (i & 3)));

    /* 9 轮完整轮 */
    for (int r = 1; r <= 9; r++) {
        /* SubBytes */
        for (int i = 0; i < 16; i++) t[i] = sbox[s[i]];
        /* ShiftRows */
        s[0] = t[0];  s[4] = t[4];  s[8] = t[8];   s[12] = t[12];
        s[1] = t[5];  s[5] = t[9];  s[9] = t[13];  s[13] = t[1];
        s[2] = t[10]; s[6] = t[14]; s[10] = t[2];  s[14] = t[6];
        s[3] = t[15]; s[7] = t[3];  s[11] = t[7];  s[15] = t[11];
        /* MixColumns */
        for (int c = 0; c < 4; c++) {
            uint8_t *col = s + 4 * c;
            uint8_t a0 = col[0], a1 = col[1], a2 = col[2], a3 = col[3];
            uint8_t x = (uint8_t)(a0 ^ a1 ^ a2 ^ a3);
            col[0] = (uint8_t)(a0 ^ x ^ xtime((uint8_t)(a0 ^ a1)));
            col[1] = (uint8_t)(a1 ^ x ^ xtime((uint8_t)(a1 ^ a2)));
            col[2] = (uint8_t)(a2 ^ x ^ xtime((uint8_t)(a2 ^ a3)));
            col[3] = (uint8_t)(a3 ^ x ^ xtime((uint8_t)(a3 ^ a0)));
        }
        /* AddRoundKey */
        for (int i = 0; i < 16; i++) s[i] ^= (uint8_t)(rk[(r * 4 + (i >> 2))] >> (24 - 8 * (i & 3)));
    }

    /* 最后一轮（无 MixColumns） */
    for (int i = 0; i < 16; i++) t[i] = sbox[s[i]];
    s[0] = t[0];  s[4] = t[4];  s[8] = t[8];   s[12] = t[12];
    s[1] = t[5];  s[5] = t[9];  s[9] = t[13];  s[13] = t[1];
    s[2] = t[10]; s[6] = t[14]; s[10] = t[2];  s[14] = t[6];
    s[3] = t[15]; s[7] = t[3];  s[11] = t[7];  s[15] = t[11];
    for (int i = 0; i < 16; i++) s[i] ^= (uint8_t)(rk[(40 + (i >> 2))] >> (24 - 8 * (i & 3)));

    memcpy(out, s, 16);
}

static void inv_mix_columns(uint8_t *s)
{
    for (int c = 0; c < 4; c++) {
        uint8_t *col = s + 4 * c;
        uint8_t a0 = col[0], a1 = col[1], a2 = col[2], a3 = col[3];
        col[0] = (uint8_t)(gmul(a0, 0x0e) ^ gmul(a1, 0x0b) ^ gmul(a2, 0x0d) ^ gmul(a3, 0x09));
        col[1] = (uint8_t)(gmul(a0, 0x09) ^ gmul(a1, 0x0e) ^ gmul(a2, 0x0b) ^ gmul(a3, 0x0d));
        col[2] = (uint8_t)(gmul(a0, 0x0d) ^ gmul(a1, 0x09) ^ gmul(a2, 0x0e) ^ gmul(a3, 0x0b));
        col[3] = (uint8_t)(gmul(a0, 0x0b) ^ gmul(a1, 0x0d) ^ gmul(a2, 0x09) ^ gmul(a3, 0x0e));
    }
}

void aes128_decrypt_block(const aes128_ctx *ctx, const uint8_t in[AES_BLOCK_LEN],
                          uint8_t out[AES_BLOCK_LEN])
{
    const uint32_t *rk = ctx->rk;
    uint8_t s[AES_BLOCK_LEN];
    uint8_t t[AES_BLOCK_LEN];

    for (int i = 0; i < 16; i++) s[i] = in[i];
    /* 初始 AddRoundKey（最后一轮密钥） */
    for (int i = 0; i < 16; i++) s[i] ^= (uint8_t)(rk[(40 + (i >> 2))] >> (24 - 8 * (i & 3)));

    /* 9 轮完整轮 */
    for (int r = 9; r >= 1; r--) {
        /* InvShiftRows */
        t[0] = s[0];  t[4] = s[4];  t[8] = s[8];   t[12] = s[12];
        t[5] = s[1];  t[9] = s[5];  t[13] = s[9];  t[1] = s[13];
        t[10] = s[2]; t[14] = s[6]; t[2] = s[10];  t[6] = s[14];
        t[15] = s[3]; t[3] = s[7];  t[7] = s[11];  t[11] = s[15];
        /* InvSubBytes */
        for (int i = 0; i < 16; i++) s[i] = inv_sbox[t[i]];
        /* AddRoundKey */
        for (int i = 0; i < 16; i++) s[i] ^= (uint8_t)(rk[(r * 4 + (i >> 2))] >> (24 - 8 * (i & 3)));
        /* InvMixColumns */
        inv_mix_columns(s);
    }

    /* 最后一轮 */
    t[0] = s[0];  t[4] = s[4];  t[8] = s[8];   t[12] = s[12];
    t[5] = s[1];  t[9] = s[5];  t[13] = s[9];  t[1] = s[13];
    t[10] = s[2]; t[14] = s[6]; t[2] = s[10];  t[6] = s[14];
    t[15] = s[3]; t[3] = s[7];  t[7] = s[11];  t[11] = s[15];
    for (int i = 0; i < 16; i++) s[i] = inv_sbox[t[i]];
    for (int i = 0; i < 16; i++) s[i] ^= (uint8_t)(rk[(i >> 2)] >> (24 - 8 * (i & 3)));

    memcpy(out, s, 16);
}

void aes_cfb_init(aes_cfb_ctx *c, const uint8_t key[AES128_KEY_LEN],
                  const uint8_t iv[AES_BLOCK_LEN])
{
    aes128_set_encrypt_key(&c->aes, key);
    memcpy(c->iv, iv, AES_BLOCK_LEN);
    c->n = 0;
}

void aes_cfb_encrypt(aes_cfb_ctx *c, const uint8_t *in, uint8_t *out, size_t len)
{
    while (len--) {
        if (c->n == 0) {
            aes128_encrypt_block(&c->aes, c->iv, c->ks);
        }
        c->iv[c->n] = *out = (uint8_t)(*in ^ c->ks[c->n]);
        c->n = (c->n + 1) & 0x0f;
        in++; out++;
    }
}

void aes_cfb_decrypt(aes_cfb_ctx *c, const uint8_t *in, uint8_t *out, size_t len)
{
    while (len--) {
        if (c->n == 0) {
            aes128_encrypt_block(&c->aes, c->iv, c->ks);
        }
        *out = (uint8_t)(*in ^ c->ks[c->n]);
        c->iv[c->n] = *in;
        c->n = (c->n + 1) & 0x0f;
        in++; out++;
    }
}
